function steps(stationId: string, cycle: number, descs: [string, boolean][]): TrainingModule['steps'] {
  const per = Math.round(cycle / descs.length);
  return descs.map(([description, critical], i) => ({
    id: `${stationId}-STEP-${i + 1}`,
    seq: i + 1,
    description,
    targetTimeSec: per,
    toleranceSec: Math.max(3, Math.round(per * 0.2)),
    critical,
  }));
}

